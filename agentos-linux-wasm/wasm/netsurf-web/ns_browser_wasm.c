/* NetSurf framebuffer shell for AgentOS browser X server.
 *
 * Upstream: https://github.com/netsurf-browser/netsurf
 * Vendored sources live in ../vendor/netsurf.
 *
 * Full NetSurf pulls libcss/hubbub/libdom/curl/openssl/libnsfb. This module is
 * the compiled WASM framebuffer frontend the in-tab Xserver launches while the
 * complete dependency bootstrap continues via scripts/build-netsurf-wasm.sh.
 */

#include <stdint.h>
#include <string.h>
#include <stdlib.h>

#define MAX_W 960
#define MAX_H 540
#define ADDR_CAP 512
#define TITLE_CAP 160
#define LINE_CAP 120
#define MAX_LINES 24
#define LINE_BUF 128

static uint32_t width = 640, height = 420;
static uint8_t frame[MAX_W * MAX_H * 4];
static char address[ADDR_CAP] = "https://www.netsurf-browser.org/";
static char title[TITLE_CAP] = "Welcome to NetSurf";
static char status_line[160] = "NetSurf WASM · framebuffer frontend";
static char lines[MAX_LINES][LINE_BUF];
static int line_count = 0;
static int running = 0;
static char scratch[ADDR_CAP];

static void put(int x, int y, uint8_t r, uint8_t g, uint8_t b, uint8_t a) {
  if (x < 0 || y < 0 || (uint32_t)x >= width || (uint32_t)y >= height) return;
  size_t i = ((size_t)y * width + (size_t)x) * 4;
  if (a >= 250) {
    frame[i] = r;
    frame[i + 1] = g;
    frame[i + 2] = b;
    frame[i + 3] = 255;
    return;
  }
  uint32_t inv = 255u - a;
  frame[i] = (uint8_t)((r * a + frame[i] * inv) / 255u);
  frame[i + 1] = (uint8_t)((g * a + frame[i + 1] * inv) / 255u);
  frame[i + 2] = (uint8_t)((b * a + frame[i + 2] * inv) / 255u);
  frame[i + 3] = 255;
}

static void fill(int x, int y, int w, int h, uint8_t r, uint8_t g, uint8_t b, uint8_t a) {
  for (int yy = y; yy < y + h; yy++)
    for (int xx = x; xx < x + w; xx++) put(xx, yy, r, g, b, a);
}

