static void draw_char(int x, int y, char ch, uint8_t r, uint8_t g, uint8_t b) {
  if (ch < 32 || ch > 126) ch = '?';
  const uint8_t *gyl = GLYPH[ch - 32];
  for (int row = 0; row < 7; row++) {
    uint8_t bits = gyl[row];
    for (int col = 0; col < 5; col++) {
      if (bits & (0x10 >> col)) put(x + col, y + row, r, g, b, 255);
    }
  }
}

static void draw_text(int x, int y, const char *s, uint8_t r, uint8_t g, uint8_t b) {
  int cx = x;
  for (; *s; s++) {
    draw_char(cx, y, *s, r, g, b);
    cx += 6;
    if ((uint32_t)cx + 6 >= width) break;
  }
}

static void default_page(void) {
  line_count = 0;
  #define ADD(s) do { if (line_count < MAX_LINES) { strncpy(lines[line_count], s, LINE_BUF-1); lines[line_count][LINE_BUF-1]=0; line_count++; } } while (0)
  ADD("NetSurf");
  ADD("Small as a mouse, fast as a cheetah, and available for free.");
  ADD("");
  ADD("This is the AgentOS WASM framebuffer frontend for NetSurf.");
  ADD("Upstream project: https://github.com/netsurf-browser/netsurf");
  ADD("");
  ADD("Features in this build:");
  ADD("- Compiled with Emscripten to WebAssembly");
  ADD("- Launched as an X11 client under Aurora WM");
  ADD("- Address bar + toolbar chrome");
  ADD("- Page body text streamed from the browser fetch path");
  ADD("");
  ADD("Try navigating with the dock or restart desktop.");
  #undef ADD
}

static void render_ui(void) {
  fill(0, 0, (int)width, (int)height, 248, 250, 252, 255);
  fill(0, 0, (int)width, 36, 228, 234, 242, 255);
  fill(0, 36, (int)width, 26, 255, 255, 255, 255);
  fill(0, 62, (int)width, 1, 180, 190, 205, 255);

  fill(8, 8, 22, 20, 205, 215, 228, 255);
  fill(34, 8, 22, 20, 205, 215, 228, 255);
  fill(60, 8, 22, 20, 205, 215, 228, 255);
  fill(86, 8, 22, 20, 205, 215, 228, 255);
  draw_text(14, 13, "<", 40, 60, 85);
  draw_text(40, 13, ">", 40, 60, 85);
  draw_text(66, 13, "x", 40, 60, 85);
  draw_text(92, 13, "R", 40, 60, 85);

  fill(118, 8, (int)width - 160, 20, 255, 255, 255, 255);
  fill(118, 8, (int)width - 160, 1, 160, 175, 195, 255);
  draw_text(124, 13, address, 25, 45, 70);
  draw_text(8, 43, title, 20, 40, 65);

  fill(0, 63, (int)width, (int)height - 63 - 22, 255, 255, 255, 255);
  int y = 74;
  for (int i = 0; i < line_count; i++) {
    draw_text(14, y, lines[i], 30, 45, 60);
    y += 12;
    if (y > (int)height - 34) break;
  }

  fill(0, (int)height - 22, (int)width, 22, 232, 238, 245, 255);
  draw_text(8, (int)height - 15, status_line, 50, 70, 95);
}

__attribute__((export_name("netsurf_init")))
int netsurf_init(int w, int h) {
  if (w < 320) w = 320;
  if (h < 200) h = 200;
  if (w > MAX_W) w = MAX_W;
  if (h > MAX_H) h = MAX_H;
  width = (uint32_t)w;
  height = (uint32_t)h;
  running = 1;
  if (line_count == 0) default_page();
  strncpy(status_line, "NetSurf WASM framebuffer running", sizeof status_line - 1);
  status_line[sizeof status_line - 1] = 0;
  render_ui();
  return 1;
}

__attribute__((export_name("netsurf_frame_ptr")))
uint8_t *netsurf_frame_ptr(void) { return frame; }

__attribute__((export_name("netsurf_frame_len")))
int netsurf_frame_len(void) { return (int)(width * height * 4); }

__attribute__((export_name("netsurf_width")))
int netsurf_width(void) { return (int)width; }

__attribute__((export_name("netsurf_height")))
int netsurf_height(void) { return (int)height; }

__attribute__((export_name("netsurf_is_running")))
int netsurf_is_running(void) { return running; }

__attribute__((export_name("netsurf_render")))
int netsurf_render(int tick) {
  (void)tick;
  if (!running) return 0;
  render_ui();
  return 1;
}

__attribute__((export_name("netsurf_address_buf")))
char *netsurf_address_buf(void) { return scratch; }

__attribute__((export_name("netsurf_address_cap")))
int netsurf_address_cap(void) { return ADDR_CAP; }

__attribute__((export_name("netsurf_commit_address")))
int netsurf_commit_address(int len) {
  if (len < 0) len = 0;
  if (len >= ADDR_CAP) len = ADDR_CAP - 1;
  memcpy(address, scratch, (size_t)len);
  address[len] = 0;
  strncpy(status_line, "Open ", sizeof status_line - 1);
  strncat(status_line, address, sizeof status_line - strlen(status_line) - 1);
  render_ui();
  return 1;
}

__attribute__((export_name("netsurf_commit_title")))
int netsurf_commit_title(int len) {
  if (len < 0) len = 0;
  if (len >= TITLE_CAP) len = TITLE_CAP - 1;
  memcpy(title, scratch, (size_t)len);
  title[len] = 0;
  render_ui();
  return 1;
}

__attribute__((export_name("netsurf_clear_lines")))
void netsurf_clear_lines(void) { line_count = 0; }

__attribute__((export_name("netsurf_line_buf")))
char *netsurf_line_buf(void) { return scratch; }

__attribute__((export_name("netsurf_line_cap")))
int netsurf_line_cap(void) { return LINE_BUF; }

__attribute__((export_name("netsurf_add_line")))
int netsurf_add_line(int len) {
  if (line_count >= MAX_LINES) return 0;
  if (len < 0) len = 0;
  if (len >= LINE_BUF) len = LINE_BUF - 1;
  memcpy(lines[line_count], scratch, (size_t)len);
  lines[line_count][len] = 0;
  line_count++;
  return 1;
}
